package main

import "fmt"

func main() {

  var a = 1;
  fmt.Println(a);

  b := 2;
  fmt.Println(b);

  c := "hello";
  fmt.Println(c);

  e := true;
  fmt.Println(e);

  var f string;
  f = "world";
  fmt.Println(f);

  g, h := 4, "bye";
  fmt.Println(g, h);

  var i, j int = 3, 5;
  fmt.Println(i, j);

  var k string = "bye bye";
  fmt.Println(k);

}